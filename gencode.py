import argparse
import os
import sys

import hsmd_reader

VERSION = '2.0'
TICK_LEN = 100                          # the period of TIME_TICK, ms

TEMPLATES_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'templates')
HEADER_TEMPLATE = os.path.join(TEMPLATES_DIR, 'header.templ')
FOOTER_TEMPLATE = os.path.join(TEMPLATES_DIR, 'footer.templ')

# the convention comments: the key is the name of a formal comment or the
# first line of an informal one, normalised by normalize()
SECTION_INIT = 'global initialization'
SECTION_SCRIPTS = 'init scripts'
SECTION_ARGUMENTS = 'sm constructor arguments'
SECTION_LOOP = 'loop'
SECTIONS = (SECTION_INIT, SECTION_SCRIPTS, SECTION_ARGUMENTS, SECTION_LOOP)

SCRIPT_EXTENSION = '.py'
INDENT = ' ' * 4
LOOP_MARKER = INDENT * 2 + '# loop\n'


class ConvertorError(Exception):
    def __init__(self, msg):
        Exception.__init__(self)
        self.msg = msg

    def __str__(self):
        return self.msg


class ParserError(ConvertorError):
    pass


class GeneratorError(ConvertorError):
    pass


def normalize(key):
    """The key of a convention comment: case, underscores and the trailing
    colon do not matter."""
    return ' '.join(key.strip().rstrip(':').lower().replace('_', ' ').split())


class CodeGenerator:

    def __init__(self, graph_file, main=None, tick_len=TICK_LEN):
        self.graph_file = graph_file
        self.tick_len = tick_len
        try:
            machines = hsmd_reader.load(graph_file)
        except hsmd_reader.DocumentError as e:
            raise ParserError(str(e)) from e
        self.machine = self.__select(machines, main)
        self.sections = {}
        for name, body in self.machine.comments:
            self.__section(name, body.split('\n'))
        for body in self.machine.informal:
            lines = body.split('\n')
            self.__section(lines[0], lines[1:])

    def __select(self, machines, main):
        if main is None:
            return machines[0]
        for machine in machines:
            if main in (machine.id, machine.name):
                return machine
        raise ParserError("The graph {} has no state machine '{}'".format(
            self.graph_file, main))

    def __section(self, key, lines):
        key = normalize(key)
        if key not in SECTIONS:
            return
        while lines and not lines[0].strip():
            lines = lines[1:]
        while lines and not lines[-1].strip():
            lines = lines[:-1]
        self.sections.setdefault(key, []).extend(line.rstrip() for line in lines)

    def __lines(self, key):
        return self.sections.get(key, [])

    # ------------------------------------------------------------------------

    @classmethod
    def __w(cls, f, text=''):
        f.write(text + '\n')

    @classmethod
    def __insert_file(cls, f, filename):
        with open(filename, encoding='utf-8') as input_file:
            f.write(input_file.read())

    def __write_technical_info(self, f):
        self.__w(f, "# The program of the state machine '{}' from {}".format(
            self.machine.name, os.path.basename(self.graph_file)))
        self.__w(f, '# Generated by HSM-to-Python version {}'.format(VERSION))
        self.__w(f)

    def __write_constants(self, f):
        self.__w(f)
        self.__w(f, 'DIAGRAM = {!r}'.format(os.path.abspath(self.graph_file)))
        self.__w(f, 'MAIN = {!r}'.format(self.machine.id))
        self.__w(f, 'TICK_LEN = {}                 # the period of TIME_TICK, ms'.format(
            self.tick_len))

    def __write_section(self, f, title, lines):
        if not lines:
            return
        self.__w(f)
        self.__w(f, '# {}:'.format(title))
        for line in lines:
            self.__w(f, line)

    def __write_arguments(self, f):
        lines = []
        for line in self.__lines(SECTION_ARGUMENTS):
            if not line.strip():
                continue
            if '=' not in line:
                raise GeneratorError("Bad constructor argument '{}'".format(line))
            var, value = (s.strip() for s in line.split('=', 1))
            lines.append('{} = {}'.format(var, value))
        self.__write_section(f, 'Constructor arguments', lines)

    def __write_scripts(self, f):
        names = [line.strip() for line in self.__lines(SECTION_SCRIPTS)
                 if line.strip().endswith(SCRIPT_EXTENSION)]
        if not names:
            return
        path = os.path.dirname(os.path.abspath(self.graph_file))
        self.__w(f)
        self.__w(f, '# Init scripts:')
        for name in names:
            filename = os.path.join(path, name)
            if not os.path.isfile(filename):
                raise GeneratorError('Cannot open the imported Python file {}'.format(filename))
            self.__w(f)
            self.__w(f, '# imported from {}'.format(name))
            self.__insert_file(f, filename)

    def __write_footer(self, f):
        with open(FOOTER_TEMPLATE, encoding='utf-8') as footer:
            text = footer.read()
        loop = ''.join(INDENT * 2 + line + '\n' if line.strip() else '\n'
                       for line in self.__lines(SECTION_LOOP))
        if LOOP_MARKER not in text:
            raise GeneratorError('The footer template has no loop marker')
        f.write(text.replace(LOOP_MARKER, loop))

    def generate_code(self, target=None):
        """Write the program to the file, or to the standard output."""
        f = open(target, 'w', encoding='utf-8') if target is not None else sys.stdout
        try:
            self.__write_technical_info(f)
            self.__insert_file(f, HEADER_TEMPLATE)
            self.__write_constants(f)
            self.__write_arguments(f)
            self.__write_section(f, 'Global initialization', self.__lines(SECTION_INIT))
            self.__write_scripts(f)
            self.__write_footer(f)
        finally:
            if target is not None:
                f.close()


def arguments(description):
    """The command line shared by the generator and the runner."""
    parser = argparse.ArgumentParser(description=description)
    parser.add_argument('graph', help='the diagram (CyberiadaML or yEd GraphML)')
    parser.add_argument('--main', metavar='NAME',
                        help='the state machine to run (default: the first one)')
    parser.add_argument('--tick', metavar='MS', type=int, default=TICK_LEN,
                        help='the period of the TIME_TICK event, ms (default: {})'.format(
                            TICK_LEN))
    return parser


def main():
    parser = arguments('Generate the Python program of a state machine diagram.')
    parser.add_argument('output', nargs='?', help='the program file (default: stdout)')
    args = parser.parse_args()
    try:
        CodeGenerator(args.graph, main=args.main, tick_len=args.tick).generate_code(args.output)
    except ParserError as e:
        sys.stderr.write('Graph parsing error: {}\n'.format(e))
        return 1
    except GeneratorError as e:
        sys.stderr.write('Code generating error: {}\n'.format(e))
        return 2
    return 0


if __name__ == '__main__':
    sys.exit(main())
